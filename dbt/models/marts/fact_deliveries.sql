select
    shipment_id,
    order_id,
    md5(customer_id) as customer_key,
    md5(coalesce(carrier_name, '__missing__')) as carrier_key,
    md5(distribution_center_id) as distribution_center_key,
    md5(destination_region) as location_key,
    md5(service_type) as service_type_key,
    to_char(order_at::date, 'YYYYMMDD')::integer as order_date_key,
    to_char(shipped_at::date, 'YYYYMMDD')::integer as shipped_date_key,
    to_char(promised_delivery_at::date, 'YYYYMMDD')::integer as promised_delivery_date_key,
    case when delivered_at is not null then to_char(delivered_at::date, 'YYYYMMDD')::integer end as delivered_date_key,
    order_at,
    shipped_at,
    promised_delivery_at,
    delivered_at,
    delivery_status,
    delivery_attempts,
    quantity,
    weight_kg,
    freight_amount,
    event_count,
    exception_count,
    failure_reason,
    order_to_ship_hours,
    ship_to_delivery_hours,
    delivery_delay_days,
    is_on_time,
    is_valid_for_sla,
    is_orphan_order,
    is_unknown_carrier,
    is_delivery_before_shipment,
    is_delivered_without_timestamp,
    has_invalid_order,
    source_batch_id,
    _load_id,
    _ingested_at
from {{ ref('int_deliveries_enriched') }}
